#!/usr/bin/env node
// Copies the rules engine into supabase/functions/_shared/rules-engine, so the Edge Functions run the very same
// code as the browser (P2-2).
//
// Why a copy: Deno, which runs Edge Functions, needs the file extension on every relative import ('./core.ts'),
// while the engine is written for Vite and TypeScript's bundler resolution ('./core'). Deploying also bundles only
// what is inside supabase/functions. So this script copies every engine source file except the tests, adding
// '.ts' to its relative imports and a header saying where it came from. Nothing else changes.
//
//   pnpm engine:sync    write the copy (run it after changing packages/rules-engine)
//   pnpm engine:check   fail if the copy is out of date (CI runs this)
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SOURCE = 'packages/rules-engine/src';
const TARGET = 'supabase/functions/_shared/rules-engine';
const check = process.argv.includes('--check');

const HEADER = `// GENERATED by scripts/sync-engine.mjs from ${SOURCE}. Do not edit: change the engine and run pnpm engine:sync.\n`;

const wanted = new Map(
  readdirSync(SOURCE)
    .filter(f => f.endsWith('.ts') && !f.endsWith('.test.ts') && f !== 'simulation.ts')
    .map(f => {
      const code = readFileSync(join(SOURCE, f), 'utf8')
        // from './core' -> from './core.ts' (relative imports only, and only those without an extension)
        .replace(/(from\s+['"])(\.{1,2}\/[^'"]+?)(?<!\.ts|\.json)(['"])/g, '$1$2.ts$3');
      return [f, HEADER + code];
    }),
);

const present = existsSync(TARGET) ? readdirSync(TARGET).filter(f => f.endsWith('.ts')) : [];
const stale = [
  ...[...wanted].filter(([f, code]) => !present.includes(f) || readFileSync(join(TARGET, f), 'utf8') !== code),
  ...present.filter(f => !wanted.has(f)).map(f => [f, null]),
];

if (check) {
  if (stale.length) {
    console.error(`The engine copy in ${TARGET} is out of date (${stale.map(([f]) => f).join(', ')}).`);
    console.error('Run pnpm engine:sync and commit the result.');
    process.exit(1);
  }
  console.log(`${TARGET} matches ${SOURCE}.`);
} else {
  mkdirSync(TARGET, { recursive: true });
  for (const [f, code] of stale) {
    if (code === null) rmSync(join(TARGET, f));
    else writeFileSync(join(TARGET, f), code);
  }
  console.log(stale.length ? `Updated ${stale.map(([f]) => f).join(', ')}.` : 'Already up to date.');
}
